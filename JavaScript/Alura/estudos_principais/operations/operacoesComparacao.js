const idadeVinny = 36
const minhaIdade = "18"

//Operador de Igualdade
const igualdade = idadeVinny == minhaIdade
console.log('São iguais?: ', igualdade)

//Operador de Diferença
const diferente = idadeVinny != minhaIdade
console.log('Idade do Vinny é diferente da minha?: ', diferente)

//Operador de Maior que
const maior = idadeVinny > minhaIdade
console.log('Idade do Vinny é maior que a minha?: ', maior)

//Operador de Menor que 
const menor = idadeVinny < minhaIdade
console.log('Idade do Vinny é menor que a minha?: ', menor)

//Operador de Maior ou Igual que
const maiorIgual = idadeVinny >= minhaIdade
console.log('Idade do Vinny é maior ou igual a minha?: ', maiorIgual)

//Operador de Menor ou Igual que
const menorIgual = idadeVinny <= minhaIdade
console.log('Idade do Vinny é menor ou igual a minha?: ', menorIgual)

//Operador Comparação Estrita Igual
const comparacaoEstritaIgual = idadeVinny === minhaIdade
console.log('A idade do Vinny e a minha não estritamente iguais?: ', comparacaoEstritaIgual)

//Operador Comparação Estrita Diferente
const comparacaoEstritaDiferente = idadeVinny !== minhaIdade
console.log('A idade do Vinny e a minha são estritamente diferentes?: ', comparacaoEstritaDiferente)